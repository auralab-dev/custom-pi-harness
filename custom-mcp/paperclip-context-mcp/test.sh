#!/usr/bin/env bash
# End-to-end MCP integration test for paperclip-context-mcp.
#
# This script talks to the MCP server over stdio JSON-RPC. Before the MCP
# session it performs two read-only curl preflights (API connectivity and, when
# supplied, heartbeat-run status). It does not require jq.
#
# WARNING: the full test creates and mutates real Paperclip data in
# PAPERCLIP_COMPANY_ID. Run only against a disposable/test company.

set -uo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
SERVER_ENTRY="$ROOT_DIR/dist/index.js"
MCP_PROTOCOL_VERSION="${MCP_PROTOCOL_VERSION:-2025-11-25}"
MCP_READ_TIMEOUT="${PAPERCLIP_TEST_MCP_TIMEOUT_SECONDS:-30}"
MAIN_INLINE_THRESHOLD="${PAPERCLIP_TEST_INLINE_THRESHOLD:-30000}"

PASS_COUNT=0
FAIL_COUNT=0
SKIP_COUNT=0
REQUEST_ID=0
LAST_RESPONSE=""
MCP_PID=""
MCP_OUT_FD=""
MCP_IN_FD=""
SERVER_STDERR=""
SERVER_TELEMETRY=""
MCP_PROTOCOL_IN_LOG=""
MCP_PROTOCOL_OUT_LOG=""
TEST_DIR=""
ISSUE_ID=""
CHECKOUT_ISSUE_ID=""
LARGE_ISSUE_ID=""
LARGE_SNAPSHOT_PATH=""
LONG_DESCRIPTION_WORDS=0
ISSUE_CHECKED_OUT=0
RUN_STATUS="unknown"
RUN_IS_LIVE=0

if (( BASH_VERSINFO[0] < 4 )); then
  printf 'ERROR: test.sh requires Bash 4+ (coproc is used). Current: %s\n' "$BASH_VERSION" >&2
  exit 2
fi

declare -A CALLED_TOOLS=()
declare -A SUCCESS_TOOLS=()

EXPECTED_TOOLS=(
  paperclip_context
  paperclip_inbox
  paperclip_issue
  paperclip_heartbeat_context
  paperclip_issues
  paperclip_issue_create
  paperclip_issue_update
  paperclip_issue_checkout
  paperclip_issue_release
  paperclip_comments
  paperclip_comment_add
  paperclip_documents
  paperclip_document
  paperclip_document_put
  paperclip_agents
  paperclip_raw
)

if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
  C_RESET=$'\033[0m'
  C_DIM=$'\033[2m'
  C_BLUE=$'\033[34m'
  C_GREEN=$'\033[32m'
  C_YELLOW=$'\033[33m'
  C_RED=$'\033[31m'
else
  C_RESET=''
  C_DIM=''
  C_BLUE=''
  C_GREEN=''
  C_YELLOW=''
  C_RED=''
fi

log()      { printf '%s[%s]%s %s\n' "$C_BLUE" "$(date '+%H:%M:%S')" "$C_RESET" "$*"; }
log_dim()  { printf '%s[%s] %s%s\n' "$C_DIM" "$(date '+%H:%M:%S')" "$*" "$C_RESET"; }
log_warn() { printf '%s[WARN]%s %s\n' "$C_YELLOW" "$C_RESET" "$*"; }
log_err()  { printf '%s[FAIL]%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; }

pass() {
  PASS_COUNT=$((PASS_COUNT + 1))
  printf '%s[PASS]%s %s\n' "$C_GREEN" "$C_RESET" "$*"
}

fail() {
  FAIL_COUNT=$((FAIL_COUNT + 1))
  log_err "$*"
}

skip() {
  SKIP_COUNT=$((SKIP_COUNT + 1))
  printf '%s[SKIP]%s %s\n' "$C_YELLOW" "$C_RESET" "$*"
}

die() {
  log_err "$*"
  exit 2
}

json_escape() {
  local s="$1"
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//$'\n'/\\n}
  s=${s//$'\r'/\\r}
  s=${s//$'\t'/\\t}
  printf '%s' "$s"
}

json_string() {
  printf '"%s"' "$(json_escape "$1")"
}

response_has_protocol_error() {
  [[ "$1" == *'"error":{'* ]]
}

response_has_tool_error() {
  [[ "$1" == *'"isError":true'* ]]
}

response_preview() {
  local s="$1"
  local max="${2:-1600}"
  if (( ${#s} > max )); then
    printf '%s…' "${s:0:max}"
  else
    printf '%s' "$s"
  fi
}

extract_text_field_simple() {
  # Intended for compact ACK/path results generated by this MCP. It is not a
  # general JSON parser. These strings contain no embedded quote characters.
  local s="$1"
  local marker='"text":"'
  [[ "$s" == *"$marker"* ]] || return 1
  s="${s#*"$marker"}"
  printf '%s' "${s%%\"*}"
}

extract_created_ref() {
  local s="$1"
  [[ "$s" == *'Created '* ]] || return 1
  s="${s#*Created }"
  printf '%s' "${s%% *}"
}

require_env() {
  local name="$1"
  if [[ -z "${!name:-}" ]]; then
    die "Missing required environment variable: $name"
  fi
}

prepare_long_description() {
  # Build a payload that is guaranteed to cross the MCP's *rendered* token
  # threshold while keeping the HTTP request reasonably small. The estimator
  # counts lexical units at ~1.5 tokens each, so repeated short non-ASCII words
  # cross the default 30k threshold at roughly 20k words (~60-70 KiB UTF-8).
  #
  # PAPERCLIP_TEST_LONG_DESCRIPTION_WORDS can override the generated size when
  # testing a custom threshold or server request-body limit.
  local threshold="$1"
  local begin_marker="$2"
  local end_marker="$3"
  local fill=''

  if [[ -n "${PAPERCLIP_TEST_LONG_DESCRIPTION_WORDS:-}" ]]; then
    LONG_DESCRIPTION_WORDS="$PAPERCLIP_TEST_LONG_DESCRIPTION_WORDS"
  elif (( threshold > 0 )); then
    LONG_DESCRIPTION_WORDS=$(( (threshold * 2 + 2) / 3 + 2500 ))
  else
    LONG_DESCRIPTION_WORDS=22500
  fi

  if ! [[ "$LONG_DESCRIPTION_WORDS" =~ ^[0-9]+$ ]] || (( LONG_DESCRIPTION_WORDS < 1 )); then
    die "PAPERCLIP_TEST_LONG_DESCRIPTION_WORDS must be a positive integer"
  fi

  printf -v fill '%*s' "$LONG_DESCRIPTION_WORDS" ''
  fill="${fill// /é }"
  LONG_DESCRIPTION="${begin_marker}"$'\n'"${fill}"$'\n'"${end_marker}"
}

stop_server() {
  if [[ -n "$MCP_IN_FD" ]]; then
    eval "exec ${MCP_IN_FD}>&-" 2>/dev/null || true
    MCP_IN_FD=""
  fi
  if [[ -n "$MCP_OUT_FD" ]]; then
    eval "exec ${MCP_OUT_FD}<&-" 2>/dev/null || true
    MCP_OUT_FD=""
  fi
  if [[ -n "$MCP_PID" ]]; then
    if kill -0 "$MCP_PID" 2>/dev/null; then
      kill "$MCP_PID" 2>/dev/null || true
    fi
    wait "$MCP_PID" 2>/dev/null || true
    MCP_PID=""
  fi
}

cleanup() {
  stop_server
  if [[ -n "${TEST_DIR:-}" ]]; then
    log_dim "Integration-test logs kept at: $TEST_DIR"
  fi
}
trap cleanup EXIT INT TERM

start_server() {
  local threshold="$1"
  local label="$2"

  stop_server

  SERVER_STDERR="$TEST_DIR/${label}.server.stderr.log"
  SERVER_TELEMETRY="$TEST_DIR/${label}.telemetry.jsonl"
  MCP_PROTOCOL_IN_LOG="$TEST_DIR/${label}.mcp.stdin.jsonl"
  MCP_PROTOCOL_OUT_LOG="$TEST_DIR/${label}.mcp.stdout.jsonl"
  : > "$SERVER_STDERR"
  : > "$SERVER_TELEMETRY"
  : > "$MCP_PROTOCOL_IN_LOG"
  : > "$MCP_PROTOCOL_OUT_LOG"

  local headers_json="${PAPERCLIP_MCP_HEADERS_JSON:-}"
  if [[ -z "$headers_json" ]]; then
    headers_json='{"X-Paperclip-MCP-Integration-Test":"bash-test"}'
    log_dim "PAPERCLIP_MCP_HEADERS_JSON unset; injecting a harmless integration-test header for this server process."
  else
    log_dim "Using caller-provided PAPERCLIP_MCP_HEADERS_JSON (value intentionally not logged)."
  fi

  log "Starting MCP server ($label, inline threshold=$threshold estimated tokens)"

  coproc PC_MCP {
    PAPERCLIP_MCP_INLINE_TOKEN_THRESHOLD="$threshold" \
    PAPERCLIP_MCP_ARTIFACT_DIR="$TEST_DIR/artifacts" \
    PAPERCLIP_MCP_TELEMETRY=1 \
    PAPERCLIP_MCP_TELEMETRY_FILE="$SERVER_TELEMETRY" \
    PAPERCLIP_MCP_HEADERS_JSON="$headers_json" \
      node "$SERVER_ENTRY" 2>>"$SERVER_STDERR"
  }

  MCP_PID="$PC_MCP_PID"
  MCP_OUT_FD="${PC_MCP[0]}"
  MCP_IN_FD="${PC_MCP[1]}"

  local i
  for ((i = 0; i < 100; i++)); do
    if grep -Fq '"status":"started"' "$SERVER_STDERR" 2>/dev/null; then
      pass "MCP server started: $label"
      if grep -Eq '"custom_header_count":[1-9][0-9]*' "$SERVER_STDERR"; then
        pass "MCP server loaded one or more custom request headers ($label)"
      else
        log_warn "MCP startup reports custom_header_count=0; custom-header request path is not exercised in this session"
      fi
      return 0
    fi
    if ! kill -0 "$MCP_PID" 2>/dev/null; then
      fail "MCP server exited during startup ($label)"
      sed -n '1,160p' "$SERVER_STDERR" >&2 || true
      return 1
    fi
    sleep 0.05
  done

  fail "Timed out waiting for MCP startup marker ($label)"
  sed -n '1,160p' "$SERVER_STDERR" >&2 || true
  return 1
}

send_notification() {
  local method="$1"
  local params="${2:-}"
  if [[ -n "$params" ]]; then
    printf '{"jsonrpc":"2.0","method":%s,"params":%s}\n' \
      "$(json_string "$method")" "$params" >&${MCP_IN_FD}
  else
    printf '{"jsonrpc":"2.0","method":%s}\n' \
      "$(json_string "$method")" >&${MCP_IN_FD}
  fi
}

mcp_request() {
  local method="$1"
  local params="${2-}"
  [[ -n "$params" ]] || params='{}'
  local line

  REQUEST_ID=$((REQUEST_ID + 1))
  local id="$REQUEST_ID"

  local request_line
  printf -v request_line '{"jsonrpc":"2.0","id":%d,"method":%s,"params":%s}' \
    "$id" "$(json_string "$method")" "$params"
  printf '%s\n' "$request_line" >> "$MCP_PROTOCOL_IN_LOG"
  printf '%s\n' "$request_line" >&${MCP_IN_FD}

  while true; do
    if ! IFS= read -r -t "$MCP_READ_TIMEOUT" line <&${MCP_OUT_FD}; then
      fail "Timed out waiting ${MCP_READ_TIMEOUT}s for MCP response to $method (request $id)"
      if [[ -n "$MCP_PID" ]] && ! kill -0 "$MCP_PID" 2>/dev/null; then
        log_err "MCP process is no longer running."
      fi
      sed -n '1,220p' "$SERVER_STDERR" >&2 || true
      LAST_RESPONSE=""
      return 1
    fi

    printf '%s\n' "$line" >> "$MCP_PROTOCOL_OUT_LOG"

    # Requests are sequential; ignore any non-response protocol messages until
    # the response carrying this request id arrives.
    if [[ "$line" == *"\"id\":$id"* ]]; then
      LAST_RESPONSE="$line"
      return 0
    fi
  done
}

initialize_mcp() {
  local params
  printf -v params '{"protocolVersion":%s,"capabilities":{},"clientInfo":{"name":"paperclip-context-mcp-bash-test","version":"1.0"}}' \
    "$(json_string "$MCP_PROTOCOL_VERSION")"

  if ! mcp_request initialize "$params"; then
    return 1
  fi
  if response_has_protocol_error "$LAST_RESPONSE"; then
    fail "MCP initialize returned protocol error: $(response_preview "$LAST_RESPONSE")"
    return 1
  fi

  send_notification notifications/initialized
  pass "MCP initialize handshake"
  return 0
}

tool_call() {
  local name="$1"
  local args="${2-}"
  [[ -n "$args" ]] || args='{}'
  local params
  CALLED_TOOLS["$name"]=1

  printf -v params '{"name":%s,"arguments":%s}' "$(json_string "$name")" "$args"
  mcp_request tools/call "$params"
}

run_tool_ok() {
  local label="$1"
  local name="$2"
  local args="${3-}"
  [[ -n "$args" ]] || args='{}'

  log "Tool: $name — $label"
  if ! tool_call "$name" "$args"; then
    fail "$name transport call failed — $label"
    return 1
  fi
  if response_has_protocol_error "$LAST_RESPONSE"; then
    fail "$name protocol error — $label: $(response_preview "$LAST_RESPONSE")"
    return 1
  fi
  if response_has_tool_error "$LAST_RESPONSE"; then
    fail "$name returned isError=true — $label: $(response_preview "$LAST_RESPONSE")"
    return 1
  fi

  SUCCESS_TOOLS["$name"]=1
  pass "$name — $label"
  return 0
}

run_tool_expected_error() {
  local label="$1"
  local name="$2"
  local args="${3-}"
  [[ -n "$args" ]] || args='{}'

  log "Tool (expected error): $name — $label"
  if ! tool_call "$name" "$args"; then
    fail "$name transport failed while testing expected error — $label"
    return 1
  fi
  if response_has_protocol_error "$LAST_RESPONSE"; then
    fail "$name produced protocol error rather than tool error — $label: $(response_preview "$LAST_RESPONSE")"
    return 1
  fi
  if ! response_has_tool_error "$LAST_RESPONSE"; then
    fail "$name unexpectedly succeeded — $label: $(response_preview "$LAST_RESPONSE")"
    return 1
  fi
  pass "$name correctly rejected invalid request — $label"
  return 0
}

assert_tool_catalog() {
  log "Listing MCP tools"
  if ! mcp_request tools/list '{}'; then
    return 1
  fi
  if response_has_protocol_error "$LAST_RESPONSE"; then
    fail "tools/list returned protocol error: $(response_preview "$LAST_RESPONSE")"
    return 1
  fi

  local tool
  local missing=0
  for tool in "${EXPECTED_TOOLS[@]}"; do
    if [[ "$LAST_RESPONSE" == *"$tool"* ]]; then
      pass "registered tool: $tool"
    else
      fail "missing registered tool: $tool"
      missing=1
    fi
  done
  return "$missing"
}

assert_telemetry_operation() {
  local file="$1"
  local op="$2"
  if grep -Fq "\"operation\":\"$op\"" "$file"; then
    pass "telemetry contains operation: $op"
    return 0
  fi
  fail "telemetry missing operation: $op"
  return 1
}


# Build a curl header file from PAPERCLIP_MCP_HEADERS_JSON without printing
# values or putting Cloudflare service-token secrets in curl's argv. Node is
# already required by the MCP and is only used here as a strict JSON decoder.
write_curl_header_file() {
  local out_file="$1"
  : > "$out_file"
  chmod 0600 "$out_file" 2>/dev/null || true

  if [[ -n "${PAPERCLIP_MCP_HEADERS_JSON:-}" ]]; then
    if ! PAPERCLIP_MCP_HEADERS_JSON="$PAPERCLIP_MCP_HEADERS_JSON" node - <<'NODE' >> "$out_file"; then
const raw = process.env.PAPERCLIP_MCP_HEADERS_JSON ?? '';
let parsed;
try {
  parsed = JSON.parse(raw);
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`Invalid PAPERCLIP_MCP_HEADERS_JSON: ${message}\n`);
  process.exit(2);
}
if (parsed === null || Array.isArray(parsed) || typeof parsed !== 'object') {
  process.stderr.write('PAPERCLIP_MCP_HEADERS_JSON must be a JSON object.\n');
  process.exit(2);
}
for (const [name, value] of Object.entries(parsed)) {
  if (typeof value !== 'string') {
    process.stderr.write(`Custom header ${name} must have a string value.\n`);
    process.exit(2);
  }
  if (!name.trim() || /[\r\n:]/.test(name) || /[\r\n]/.test(value)) {
    process.stderr.write(`Custom header ${JSON.stringify(name)} is not safe for an HTTP header file.\n`);
    process.exit(2);
  }
  const lower = name.toLowerCase();
  if (lower === 'authorization' || lower === 'x-paperclip-run-id') continue;
  process.stdout.write(`${name}: ${value}\n`);
}
NODE
      return 1
    fi
  fi

  # Paperclip identity is adapter-owned and applied after custom headers by the
  # TypeScript client. Mirror that behavior in curl.
  printf 'Authorization: Bearer %s\n' "$PAPERCLIP_API_KEY" >> "$out_file"
  printf 'Accept: application/json, text/plain;q=0.9, */*;q=0.1\n' >> "$out_file"
}

paperclip_preflight_url() {
  local base="${PAPERCLIP_API_URL%/}"
  if [[ "$base" == */api ]]; then
    printf '%s/companies/%s/issues?limit=1' "$base" "$PAPERCLIP_COMPANY_ID"
  else
    printf '%s/api/companies/%s/issues?limit=1' "$base" "$PAPERCLIP_COMPANY_ID"
  fi
}

api_connectivity_preflight() {
  command -v curl >/dev/null 2>&1 || die "curl is required for the API connectivity preflight"

  local url status body_file headers_file request_headers_file
  url="$(paperclip_preflight_url)"
  body_file="$TEST_DIR/api-preflight.body"
  headers_file="$TEST_DIR/api-preflight.headers"
  request_headers_file="$TEST_DIR/api-preflight.request.headers"
  : > "$body_file"
  : > "$headers_file"

  if ! write_curl_header_file "$request_headers_file"; then
    fail "Could not prepare custom headers for API preflight"
    return 1
  fi

  log "Preflight: Paperclip API connectivity via curl"
  log_dim "GET $url"
  log_dim "Request-header values are redacted; redirects are intentionally NOT followed."

  if ! status="$(curl \
    --silent \
    --show-error \
    --connect-timeout "${PAPERCLIP_TEST_CURL_CONNECT_TIMEOUT_SECONDS:-10}" \
    --max-time "${PAPERCLIP_TEST_CURL_TIMEOUT_SECONDS:-30}" \
    --dump-header "$headers_file" \
    --output "$body_file" \
    --write-out '%{http_code}' \
    --header "@$request_headers_file" \
    "$url")"; then
    fail "curl could not reach Paperclip API"
    log_err "Inspect response headers: $headers_file"
    log_err "Inspect response body: $body_file"
    return 1
  fi

  if [[ "$status" =~ ^2[0-9][0-9]$ ]]; then
    pass "Paperclip API connectivity (HTTP $status)"
    return 0
  fi

  fail "Paperclip API connectivity returned HTTP $status"
  log_err "Inspect response headers: $headers_file"
  log_err "Inspect response body: $body_file"
  if [[ -s "$body_file" ]]; then
    log_err "Response preview: $(LC_ALL=C head -c 1200 "$body_file" | tr '\n' ' ')"
  fi
  return 1
}


paperclip_run_url() {
  local base="${PAPERCLIP_API_URL%/}"
  if [[ "$base" == */api ]]; then
    printf '%s/heartbeat-runs/%s' "$base" "$PAPERCLIP_RUN_ID"
  else
    printf '%s/api/heartbeat-runs/%s' "$base" "$PAPERCLIP_RUN_ID"
  fi
}

extract_json_string_field_file() {
  local file="$1"
  local key="$2"
  LC_ALL=C grep -Eo '"'"$key"'"[[:space:]]*:[[:space:]]*"[^"]*"' "$file" 2>/dev/null \
    | head -n 1 \
    | sed -E 's/^[^:]+:[[:space:]]*"([^"]*)"$/\1/'
}

heartbeat_run_preflight() {
  local url http_status body_file headers_file request_headers_file
  url="$(paperclip_run_url)"
  body_file="$TEST_DIR/run-preflight.body"
  headers_file="$TEST_DIR/run-preflight.headers"
  request_headers_file="$TEST_DIR/run-preflight.request.headers"
  : > "$body_file"
  : > "$headers_file"

  if ! write_curl_header_file "$request_headers_file"; then
    log_warn "Could not prepare headers for heartbeat-run preflight; run liveness will be unknown"
    return 0
  fi

  log "Preflight: heartbeat-run attribution/liveness"
  log_dim "GET $url"

  if ! http_status="$(curl \
    --silent \
    --show-error \
    --connect-timeout "${PAPERCLIP_TEST_CURL_CONNECT_TIMEOUT_SECONDS:-10}" \
    --max-time "${PAPERCLIP_TEST_CURL_TIMEOUT_SECONDS:-30}" \
    --dump-header "$headers_file" \
    --output "$body_file" \
    --write-out '%{http_code}' \
    --header "@$request_headers_file" \
    "$url")"; then
    log_warn "Could not read heartbeat run; live ownership tests will be treated as unavailable"
    return 0
  fi

  if [[ ! "$http_status" =~ ^2[0-9][0-9]$ ]]; then
    log_warn "Heartbeat run lookup returned HTTP $http_status; live ownership tests will be treated as unavailable"
    log_dim "Inspect: $body_file"
    return 0
  fi

  RUN_STATUS="$(extract_json_string_field_file "$body_file" status || true)"
  local run_agent run_company
  run_agent="$(extract_json_string_field_file "$body_file" agentId || true)"
  run_company="$(extract_json_string_field_file "$body_file" companyId || true)"

  if [[ -n "$run_agent" && "$run_agent" != "$PAPERCLIP_AGENT_ID" ]]; then
    fail "PAPERCLIP_RUN_ID belongs to agent $run_agent, not PAPERCLIP_AGENT_ID=$PAPERCLIP_AGENT_ID"
  fi
  if [[ -n "$run_company" && "$run_company" != "$PAPERCLIP_COMPANY_ID" ]]; then
    fail "PAPERCLIP_RUN_ID belongs to company $run_company, not PAPERCLIP_COMPANY_ID=$PAPERCLIP_COMPANY_ID"
  fi

  if [[ -z "$RUN_STATUS" ]]; then
    RUN_STATUS="unknown"
    log_warn "Could not extract heartbeat run status; ownership-sensitive lifecycle checks will not be assumed live"
    return 0
  fi

  case "$RUN_STATUS" in
    succeeded|interrupted|failed|cancelled|timed_out)
      RUN_IS_LIVE=0
      log_warn "Heartbeat run is terminal: $RUN_STATUS"
      log_warn "Paperclip may clear checkout/execution locks owned by a terminal run before the next protected mutation."
      log_warn "The suite will still exercise every MCP tool, but will not require checkout→update/release ownership semantics."
      ;;
    *)
      RUN_IS_LIVE=1
      pass "heartbeat run is non-terminal: $RUN_STATUS"
      ;;
  esac
}

# ---- Preflight ------------------------------------------------------------

log "Paperclip Context MCP integration test"
log_warn "This test CREATES and MUTATES data in PAPERCLIP_COMPANY_ID. Use a disposable/test company."

if [[ "${PAPERCLIP_TEST_ALLOW_WRITES:-0}" != "1" ]]; then
  die "Set PAPERCLIP_TEST_ALLOW_WRITES=1 to confirm the target company is disposable."
fi

for name in \
  PAPERCLIP_API_URL \
  PAPERCLIP_API_KEY \
  PAPERCLIP_COMPANY_ID \
  PAPERCLIP_AGENT_ID \
  PAPERCLIP_RUN_ID; do
  require_env "$name"
done

log_dim "API URL: $PAPERCLIP_API_URL"
log_dim "Company: $PAPERCLIP_COMPANY_ID"
log_dim "Agent: $PAPERCLIP_AGENT_ID"
log_dim "Run: $PAPERCLIP_RUN_ID"
log_dim "API key: present (redacted)"
if [[ -n "${PAPERCLIP_MCP_HEADERS_JSON:-}" ]]; then
  log_dim "Custom request headers: configured (redacted)"
else
  log_dim "Custom request headers: test script will inject one harmless X-Paperclip-MCP-Integration-Test header"
fi

TEST_DIR="$(mktemp -d "${TMPDIR:-/tmp}/paperclip-context-mcp-test.XXXXXX")"
log_dim "Test work directory: $TEST_DIR"

if [[ "${PAPERCLIP_TEST_SKIP_BUILD:-0}" != "1" ]]; then
  if command -v pnpm >/dev/null 2>&1; then
    log "Building TypeScript"
    if (cd "$ROOT_DIR" && pnpm run build); then
      pass "TypeScript build"
    else
      die "TypeScript build failed; integration tests cannot continue."
    fi
  elif [[ -f "$SERVER_ENTRY" ]]; then
    log_warn "pnpm not found; using existing dist/index.js"
  else
    die "pnpm is not installed and dist/index.js is missing."
  fi
else
  log_warn "PAPERCLIP_TEST_SKIP_BUILD=1; skipping build"
fi

[[ -f "$SERVER_ENTRY" ]] || die "Missing built server: $SERVER_ENTRY"
command -v node >/dev/null 2>&1 || die "node is required"

api_connectivity_preflight || die "Paperclip API preflight failed; MCP tests were not started."
heartbeat_run_preflight

# ---- Main MCP session -----------------------------------------------------

start_server "$MAIN_INLINE_THRESHOLD" main || die "Could not start MCP server"
initialize_mcp || die "Could not initialize MCP session"
assert_tool_catalog || true

# Runtime-only read.
run_tool_ok "runtime environment" paperclip_context '{}' || true

# Agent reads: list and the current agent branch.
