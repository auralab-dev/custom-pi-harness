# Real production-threshold overflow test. A dedicated idle issue receives a
# description large enough to exceed MAIN_INLINE_THRESHOLD after compact
# Markdown rendering. We verify both sides of the contract:
#   1. the mutation that sets the huge description still returns only a tiny ACK;
#   2. a subsequent read returns only a snapshot path, while the complete
#      description is present in the immutable file on disk.
LARGE_TITLE="MCP large-description integration test $STAMP"
LARGE_DESC_BEGIN="MCP-LARGE-DESCRIPTION-BEGIN-$STAMP"
LARGE_DESC_END="MCP-LARGE-DESCRIPTION-END-$STAMP"
printf -v ARGS '{"title":%s,"description":%s,"status":"todo","priority":"low"}' \
  "$(json_string "$LARGE_TITLE")" \
  "$(json_string "Short bootstrap description; the integration test replaces this with an oversized payload.")"
if run_tool_ok "create large-description fixture issue" paperclip_issue_create "$ARGS"; then
  LARGE_ISSUE_ID="$(extract_created_ref "$LAST_RESPONSE" || true)"
else
  LARGE_ISSUE_ID=""
fi

if [[ -z "$LARGE_ISSUE_ID" || "$LARGE_ISSUE_ID" == "issue" ]]; then
  fail "Could not create/extract large-description fixture; real threshold test cannot continue"
else
  log "Large-description fixture issue: $LARGE_ISSUE_ID"
  prepare_long_description "$MAIN_INLINE_THRESHOLD" "$LARGE_DESC_BEGIN" "$LARGE_DESC_END"
  LONG_LEXICAL_ESTIMATE=$(( (LONG_DESCRIPTION_WORDS * 3 + 1) / 2 ))
  log_dim "Large description uses $LONG_DESCRIPTION_WORDS repeated words (~$LONG_LEXICAL_ESTIMATE lexical-token estimate before Markdown overhead)."

  printf -v ARGS '{"id":%s,"description":%s}' \
    "$(json_string "$LARGE_ISSUE_ID")" \
    "$(json_string "$LONG_DESCRIPTION")"
  if run_tool_ok "set oversized task description; mutation must remain compact" paperclip_issue_update "$ARGS"; then
    if [[ "$LAST_RESPONSE" != *"$LARGE_DESC_BEGIN"* && "$LAST_RESPONSE" != *"$LARGE_DESC_END"* && ${#LAST_RESPONSE} -lt 4096 ]]; then
      pass "oversized mutation response does not echo task description into model context"
    else
      fail "oversized mutation leaked description content or returned an unexpectedly large MCP result: $(response_preview "$LAST_RESPONSE" 800)"
    fi

    printf -v ARGS '{"id":%s}' "$(json_string "$LARGE_ISSUE_ID")"
    if run_tool_ok "read oversized task description at production threshold" paperclip_issue "$ARGS"; then
      LARGE_READ_RESPONSE="$LAST_RESPONSE"
      LARGE_SNAPSHOT_PATH="$(extract_text_field_simple "$LARGE_READ_RESPONSE" || true)"

      if [[ "$LARGE_READ_RESPONSE" != *"$LARGE_DESC_BEGIN"* && "$LARGE_READ_RESPONSE" != *"$LARGE_DESC_END"* && ${#LARGE_READ_RESPONSE} -lt 4096 ]]; then
        pass "oversized issue content is not returned inline to the model"
      else
        fail "oversized issue read leaked description content or returned an unexpectedly large MCP result: $(response_preview "$LARGE_READ_RESPONSE" 800)"
      fi

      if [[ -n "$LARGE_SNAPSHOT_PATH" && -f "$LARGE_SNAPSHOT_PATH" ]]; then
        pass "production-threshold issue read returned an existing snapshot path: $LARGE_SNAPSHOT_PATH"
      else
        fail "production-threshold issue read did not return an existing snapshot path: ${LARGE_SNAPSHOT_PATH:-<empty>}"
      fi

      if [[ -n "$LARGE_SNAPSHOT_PATH" ]] && grep -Fq "$LARGE_DESC_BEGIN" "$LARGE_SNAPSHOT_PATH" 2>/dev/null \
        && grep -Fq "$LARGE_DESC_END" "$LARGE_SNAPSHOT_PATH" 2>/dev/null; then
        pass "oversized task description is fully materialized in the snapshot"
      else
        fail "oversized snapshot is missing the task-description sentinel(s)"
      fi

      if [[ -n "$LARGE_SNAPSHOT_PATH" && -f "$LARGE_SNAPSHOT_PATH" ]]; then
        LARGE_SNAPSHOT_BYTES="$(wc -c < "$LARGE_SNAPSHOT_PATH" | tr -d '[:space:]')"
        if [[ "$LARGE_SNAPSHOT_BYTES" =~ ^[0-9]+$ ]] && (( LARGE_SNAPSHOT_BYTES > 50000 )); then
          pass "oversized snapshot contains substantial payload data (${LARGE_SNAPSHOT_BYTES} bytes)"
        else
          fail "oversized snapshot is unexpectedly small (${LARGE_SNAPSHOT_BYTES:-unknown} bytes)"
        fi
      fi

      LARGE_TELEMETRY_LINE="$(grep -F "\"artifact_path\":\"$LARGE_SNAPSHOT_PATH\"" "$SERVER_TELEMETRY" 2>/dev/null | tail -n 1 || true)"
      if [[ -n "$LARGE_TELEMETRY_LINE" && "$LARGE_TELEMETRY_LINE" == *'"delivery":"snapshot"'* ]]; then
        pass "production-threshold telemetry records snapshot delivery"
      else
        fail "production-threshold snapshot telemetry entry missing"
      fi

      LARGE_RENDERED_TOKEN_ESTIMATE="$(printf '%s' "$LARGE_TELEMETRY_LINE" | sed -nE 's/.*"rendered_tokens_estimate":([0-9]+).*/\1/p')"
      if [[ "$LARGE_RENDERED_TOKEN_ESTIMATE" =~ ^[0-9]+$ ]] && (( LARGE_RENDERED_TOKEN_ESTIMATE > MAIN_INLINE_THRESHOLD )); then
        pass "rendered oversized issue exceeds configured threshold (${LARGE_RENDERED_TOKEN_ESTIMATE} > ${MAIN_INLINE_THRESHOLD})"
      else
        fail "telemetry did not confirm rendered issue exceeded threshold (estimate=${LARGE_RENDERED_TOKEN_ESTIMATE:-unknown}, threshold=$MAIN_INLINE_THRESHOLD)"
      fi
    fi
  fi

  # Reduce retained test data after the assertion. This also confirms that a
  # later mutation does not depend on editing the snapshot file.
  printf -v ARGS '{"id":%s,"description":%s,"status":"done","comment":%s}' \
    "$(json_string "$LARGE_ISSUE_ID")" \
    "$(json_string "Large-description snapshot test completed; oversized payload removed during cleanup.")" \
    "$(json_string "paperclip-context-mcp oversized-description integration test completed")"
  run_tool_ok "clean up large-description fixture issue" paperclip_issue_update "$ARGS" || true
  unset LONG_DESCRIPTION
fi

